/**
 * Generate ZCode theme overrides from pi-web's theme files.
 *
 * pi-web ships 23 colour sets, each an `{light, dark}` pair of semantic colours
 * (bg, panel, text, accent, …). ZCode paints from its own `--color-*` tokens. This
 * maps one vocabulary onto the other and emits a stylesheet keyed by
 * `html[data-pi-theme="<name>"]`, so the app can switch themes by setting one
 * attribute and nothing else has to change.
 *
 * Run: node scripts/generate-pi-themes.mjs
 */

import { readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, "..");
const themesDir = process.env.PI_WEB_THEMES_DIR
  ? resolve(process.env.PI_WEB_THEMES_DIR)
  : resolve(repoRoot, "..", "pi-web-QT", "lib", "theme", "openchamber");
const outFile = join(repoRoot, "packages", "ui", "src", "pi-themes.css");

/**
 * pi-web colour key → ZCode token.
 *
 * Only the structural surfaces are mapped: ZCode derives its own subtle and
 * hover shades with `color-mix`, so pushing every one of pi-web's 17 colours
 * would fight the design system instead of joining it.
 */
const MAP = {
  bg: "--color-background",
  panel: "--color-panel",
  border: "--color-border",
  text: "--color-foreground",
  muted: "--color-foreground-subtle",
  accent: "--color-brand",
  // ZCode has no dedicated "user bubble"/"tool surface" token; `card` is its
  // low-elevation container and `surface` the recessed one used by tool bodies.
  userBg: "--color-card",
  toolBg: "--color-surface",
};

async function main() {
  const files = (await readdir(themesDir)).filter((name) => name.endsWith(".json")).sort();
  const blocks = [];
  const names = [];

  for (const file of files) {
    const raw = await readFile(join(themesDir, file), "utf8");
    const theme = JSON.parse(raw);
    const name = file.replace(/\.json$/, "");
    names.push(name);

    for (const variant of ["light", "dark"]) {
      const colors = theme[variant];
      if (!colors) continue;
      // 双选择器：html 根（整页换肤）+ 任意容器（设置→外观的预览卡片）。
      const darkSel = `[data-pi-theme="${name}"].dark, html.dark[data-pi-theme="${name}"], [data-pi-theme="${name}"][data-pi-theme-mode="dark"]`;
      const lightSel = `[data-pi-theme="${name}"]:not(.dark), html:not(.dark)[data-pi-theme="${name}"], [data-pi-theme="${name}"]:not([data-pi-theme-mode])`;
      const selector =
        variant === "dark"
          ? darkSel
          : lightSel;

      const lines = [];
      for (const [key, token] of Object.entries(MAP)) {
        const value = colors[key];
        if (typeof value === "string" && value.trim()) {
          lines.push(`  ${token}: ${value};`);
        }
      }
      // Surfaces ZCode paints explicitly; without these the frame keeps its
      // default colour and the theme looks half-applied.
      if (colors.panel) lines.push(`  --color-sidebar: ${colors.panel};`);
      if (colors.panel) lines.push(`  --color-header: ${colors.panel};`);
      if (colors.panel) lines.push(`  --color-popover: ${colors.panel};`);
      if (colors.hover) lines.push(`  --color-surface-hover: ${colors.hover};`);
      if (colors.selected) lines.push(`  --color-accent: ${colors.selected};`);

      blocks.push(`${selector} {\n${lines.join("\n")}\n}`);
    }
  }

  const header = `/* Generated by scripts/generate-pi-themes.mjs — do not edit. */
/* ${names.length} themes from pi-web. Set html[data-pi-theme] to switch. */
`;

  await writeFile(outFile, `${header}\n${blocks.join("\n\n")}\n`, "utf8");
  console.log(`wrote ${blocks.length} blocks for ${names.length} themes to ${outFile}`);
  console.log(names.join(", "));
}

main().catch((error) => {
  console.error("failed:", error);
  process.exit(1);
});
